#!/usr/bin/env python3
"""Prepare explicit, compatibility-checked host tool inputs for system_build_tool.

This runs BEFORE Soong sanitizes PATH. It never installs packages or edits sources.
Policies are trusted build configuration: probes execute candidate executables.
"""

import argparse
import hashlib
import json
import os
from pathlib import Path
import platform
import re
import shutil
import subprocess
import tempfile


MARKER = "// Generated by lineage-ur/tools/select_system_tools.py; do not edit.\n"
NAME = re.compile(r"[A-Za-z0-9_][A-Za-z0-9_.+-]*\Z")


def load_policy(path):
    policy = json.loads(Path(path).read_text())
    if not isinstance(policy, dict) or set(policy) != {"schema_version", "host", "tools"} or policy["schema_version"] != 1:
        raise ValueError("expected schema_version 1, host and tools")
    if policy["host"] != "linux_glibc_x86_64":
        raise ValueError("initial adapter supports linux_glibc_x86_64 only")
    if not isinstance(policy["tools"], list):
        raise ValueError("tools must be a list")
    names = set()
    for tool in policy["tools"]:
        if not isinstance(tool, dict) or set(tool) - {"module", "executable", "probes", "sha256", "licenses", "compatibility"}:
            raise ValueError("unknown tool policy field")
        name = tool.get("module", "")
        if not isinstance(name, str) or not NAME.fullmatch(name) or name in names:
            raise ValueError(f"invalid or duplicate module: {name!r}")
        names.add(name)
        if "compatibility" in tool and tool["compatibility"] != "android-lz4":
            raise ValueError(f"{name}: unknown compatibility profile")
        licenses = tool.get("licenses")
        if not isinstance(licenses, list) or not licenses or not all(isinstance(v, str) and v for v in licenses):
            raise ValueError(f"{name}: applicable Soong licenses must be explicit")
        executable = tool.get("executable")
        if not isinstance(executable, str) or not executable or "\0" in executable:
            raise ValueError(f"{name}: executable must be a nonempty name or absolute path")
        if "/" in executable and not Path(executable).is_absolute():
            raise ValueError(f"{name}: executable paths must be absolute")
        digest = tool.get("sha256")
        if digest is not None and (not isinstance(digest, str) or not re.fullmatch(r"[0-9a-f]{64}", digest)):
            raise ValueError(f"{name}: invalid sha256")
        probes = tool.get("probes")
        if not isinstance(probes, list) or not probes:
            raise ValueError(f"{name}: at least one compatibility probe is required")
        for probe in probes:
            if not isinstance(probe, dict) or set(probe) != {"args", "output_regex"}:
                raise ValueError(f"{name}: probe requires args and output_regex")
            if not isinstance(probe["args"], list) or not all(isinstance(v, str) and "\0" not in v for v in probe["args"]):
                raise ValueError(f"{name}: probe args must be strings")
            if not isinstance(probe["output_regex"], str) or not probe["output_regex"]:
                raise ValueError(f"{name}: nonempty output_regex required")
            re.compile(probe["output_regex"])
    return policy


def atomic_write(path, data, mode=0o644):
    path = Path(path)
    # Preserve timestamps on repeat selection of identical inputs.
    if path.exists() and path.read_bytes() == data and path.stat().st_mode & 0o777 == mode:
        return
    fd, temporary = tempfile.mkstemp(dir=path.parent, prefix=".select-")
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(data)
            os.fchmod(stream.fileno(), mode)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.unlink(temporary)


def select(tool, snapshots, timeout):
    record = {"module": tool["module"], "decision": "source"}
    candidate = shutil.which(tool["executable"])
    if not candidate:
        return record | {"reason": "executable missing"}
    candidate = Path(candidate).resolve()
    record["resolved_path"] = str(candidate)
    try:
        payload = candidate.read_bytes()
        # Scripts/interpreters and cross-architecture binaries need separate adapters.
        if len(payload) < 20 or payload[:6] != b"\x7fELF\x02\x01" or payload[18:20] != b"\x3e\x00":
            return record | {"reason": "requires a native x86-64 ELF executable"}
        digest = hashlib.sha256(payload).hexdigest()
        if tool.get("sha256") is not None and tool["sha256"] != digest:
            return record | {"reason": "sha256 mismatch", "sha256": digest}
        # Probe the snapshot itself. This also rejects tools requiring an $ORIGIN
        # layout which copying the binary would break.
        snapshot = snapshots / (tool["module"] + "-" + digest)
        atomic_write(snapshot, payload, 0o755)
        results = []
        for probe in tool["probes"]:
            with tempfile.TemporaryDirectory(prefix="lineage-tool-probe-") as work:
                result = subprocess.run(
                    [str(snapshot), *probe["args"]], cwd=work,
                    stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                    timeout=timeout, check=False, env=os.environ | {"LC_ALL": "C"},
                )
            output = result.stdout.decode("utf-8", errors="replace")
            results.append({"args": probe["args"], "returncode": result.returncode, "output": output})
            if result.returncode != 0 or not re.search(probe["output_regex"], output):
                return record | {"reason": "compatibility probe failed", "probes": results}
        compatibility = {}
        if tool.get("compatibility") == "android-lz4":
            if __package__:
                from .lz4_compat import check, Lz4CompatibilityError
            else:
                from lz4_compat import check, Lz4CompatibilityError
            try:
                compatibility = {"compatibility": check(snapshot, timeout)}
            except Lz4CompatibilityError as error:
                return record | {"reason": f"android-lz4 compatibility failed: {error}", "probes": results}
        return record | {"decision": "system", "sha256": digest, "src": "snapshots/" + snapshot.name, "probes": results} | compatibility
    except subprocess.TimeoutExpired:
        return record | {"reason": "compatibility probe timed out"}
    except OSError as error:
        return record | {"reason": str(error)}


def prepare(policy_path, output, timeout=5):
    policy = load_policy(policy_path)  # Validate everything before writing.
    if not 0 < timeout <= 30:
        raise ValueError("probe timeout must be between 0 and 30 seconds")
    if (platform.system(), platform.machine(), platform.libc_ver()[0]) != ("Linux", "x86_64", "glibc"):
        raise ValueError("policy host does not match this machine")
    output = Path(output).resolve()
    bp = output / "Android.bp"
    if bp.exists() and not bp.read_text().startswith(MARKER):
        raise ValueError("refusing to overwrite an Android.bp not generated by this tool")
    snapshots = output / "snapshots"
    snapshots.mkdir(parents=True, exist_ok=True)
    records = [select(tool, snapshots, timeout) for tool in policy["tools"]]
    lines = [MARKER]
    for tool, record in zip(policy["tools"], records):
        # A nonexistent src deliberately invokes Soong's source fallback. Keep
        # the adapter declared so deleting a snapshot also falls back cleanly.
        src = record.get("src", "unavailable/" + record["module"])
        lines.append(
            '\nsystem_build_tool {\n'
            f'    name: {json.dumps(record["module"])},\n'
            f'    src: {json.dumps(src)},\n'
            f'    licenses: {json.dumps(tool["licenses"])},\n'
            '    enabled: false,\n'
            '    target: { linux_glibc_x86_64: { enabled: true } },\n'
            '    visibility: ["//visibility:public"],\n'
            '}\n'
        )
    lock = {"schema_version": 1, "host": policy["host"],
            "policy_sha256": hashlib.sha256(Path(policy_path).read_bytes()).hexdigest(),
            "tools": records}
    atomic_write(output / "selection.json", (json.dumps(lock, indent=2) + "\n").encode())
    atomic_write(bp, "".join(lines).encode())
    return lock


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", required=True)
    parser.add_argument("--output", required=True, help="generated directory INSIDE a separate Android source tree")
    parser.add_argument("--timeout", type=float, default=5)
    args = parser.parse_args()
    try:
        result = prepare(args.policy, args.output, args.timeout)
    except (ValueError, OSError, re.error) as error:
        parser.exit(2, f"selection error: {error}\n")
    for tool in result["tools"]:
        print(f'{tool["module"]}: {tool["decision"]} ({tool.get("reason", tool.get("resolved_path"))})')


if __name__ == "__main__":
    main()
