#!/usr/bin/env python3
"""Stage reviewed host C library packages for cc_packaged_library_host."""

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import platform
import re
import subprocess

if __package__:
    from .select_system_tools import NAME, atomic_write
else:
    from select_system_tools import NAME, atomic_write

HOST = "linux_glibc_x86_64"
MARKER = "// Generated by lineage-ur/tools/select_host_libraries.py; do not edit.\n"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def is_hash(value):
    return isinstance(value, str) and re.fullmatch(r"[0-9a-f]{64}", value)


def relative(value):
    if not isinstance(value, str) or not value or "\\" in value or "\0" in value:
        raise ValueError("invalid package path")
    path = PurePosixPath(value)
    if path.is_absolute() or any(p in ("", ".", "..") for p in value.split("/")):
        raise ValueError("package paths must be normalized and relative")
    return value


def load_policy(path):
    policy = json.loads(Path(path).read_text())
    if not isinstance(policy, dict) or set(policy) != {"schema_version", "host", "libraries"}:
        raise ValueError("expected schema_version, host and libraries")
    if policy["schema_version"] != 1 or policy["host"] != HOST or not isinstance(policy["libraries"], list):
        raise ValueError("expected schema 1 and linux_glibc_x86_64 libraries")
    names = set()
    for item in policy["libraries"]:
        if not isinstance(item, dict) or set(item) != {"module", "manifest", "sha256", "licenses"}:
            raise ValueError("library policy needs module, manifest, sha256 and licenses")
        name = item["module"]
        if not isinstance(name, str) or not NAME.fullmatch(name) or name in names:
            raise ValueError("invalid or duplicate module")
        names.add(name)
        if not isinstance(item["manifest"], str) or not item["manifest"] or not is_hash(item["sha256"]):
            raise ValueError(f"{name}: manifest path and reviewed SHA-256 required")
        if not isinstance(item["licenses"], list) or not item["licenses"] or not all(isinstance(v, str) and v for v in item["licenses"]):
            raise ValueError(f"{name}: explicit applicable Soong licenses required")
    return policy


def check_archive(payload):
    if not payload.startswith(b"!<arch>\n"):
        raise ValueError("requires a regular static archive (no thin archives)")
    offset, objects = 8, 0
    while offset < len(payload):
        header = payload[offset:offset + 60]
        if len(header) != 60 or header[58:] != b"`\n":
            raise ValueError("malformed archive member header")
        size = int(header[48:58])
        if size < 0 or offset + 60 + size > len(payload):
            raise ValueError("malformed archive member size")
        member = payload[offset + 60:offset + 60 + size]
        name = header[:16].strip()
        offset += 60 + size + size % 2
        if name in (b"/", b"//", b"/SYM64/") or name.startswith(b"__.SYMDEF"):
            continue
        if name.startswith(b"#1/"):  # BSD extended filename, stored in the member.
            member = member[int(name[3:]):]
        if len(member) < 20 or member[:6] != b"\x7fELF\x02\x01" or member[16:20] != b"\x01\x00\x3e\x00":
            raise ValueError("archive members must be native x86-64 ELF objects (no bitcode)")
        objects += 1
    if not objects:
        raise ValueError("archive contains no native objects")


def inspect_package(item, policy_dir, readelf):
    manifest_path = (policy_dir / item["manifest"]).resolve()
    raw = manifest_path.read_bytes()
    if digest(raw) != item["sha256"]:
        raise ValueError("manifest checksum mismatch")
    manifest = json.loads(raw)
    required = {"schema_version", "module", "host", "source_revision", "toolchain", "configuration",
                "files", "include_dirs", "dependencies"}
    if not isinstance(manifest, dict) or not required <= manifest.keys() or set(manifest) - required - {"static", "shared"}:
        raise ValueError("invalid package manifest fields")
    if manifest["schema_version"] != 1 or manifest["module"] != item["module"] or manifest["host"] != HOST:
        raise ValueError("package identity or host mismatch")
    for key in ("source_revision", "toolchain", "configuration"):
        if not isinstance(manifest[key], str) or not manifest[key]:
            raise ValueError(f"package must record {key}")
    files = manifest["files"]
    if not isinstance(files, dict) or not files:
        raise ValueError("package file inventory required")
    payloads = {"package.json": raw}
    for name, checksum in files.items():
        relative(name)
        if name == "package.json" or not is_hash(checksum):
            raise ValueError("invalid package file checksum or reserved filename")
        source = (manifest_path.parent / name).resolve()
        if not source.is_relative_to(manifest_path.parent):
            raise ValueError("package file escapes package directory")
        payload = source.read_bytes()
        if digest(payload) != checksum:
            raise ValueError(f"file checksum mismatch: {name}")
        payloads[name] = payload
    includes = manifest["include_dirs"]
    if not isinstance(includes, list) or not includes:
        raise ValueError("explicit header include directories required")
    for directory in includes:
        relative(directory)
        if not any(name.startswith(directory + "/") for name in files):
            raise ValueError(f"header directory has no inventoried files: {directory}")
    if not any(manifest.get(kind) for kind in ("static", "shared")):
        raise ValueError("package has no library artifact")
    for kind in ("static", "shared"):
        if kind not in manifest:
            continue
        name = relative(manifest[kind])
        if name not in files:
            raise ValueError(f"{kind} artifact not inventoried")
        payload = payloads[name]
        if kind == "static":
            # Thin archives reference files outside the package; do not accept them.
            check_archive(payload)
        else:
            if len(payload) < 20 or payload[:6] != b"\x7fELF\x02\x01" or payload[16:20] != b"\x03\x00\x3e\x00":
                raise ValueError("requires a native x86-64 ELF shared library")
            if Path(name).name != item["module"] + ".so":
                raise ValueError("shared artifact must match module.so; versioned layouts need an adapter")
            info = subprocess.run([readelf, "-dW", str(manifest_path.parent / name)],
                                  capture_output=True, text=True, timeout=5, check=True,
                                  env=os.environ | {"LC_ALL": "C"}).stdout
            soname = re.search(r"\(SONAME\).*\[([^]]+)\]", info)
            if not soname or soname[1] != Path(name).name:
                raise ValueError("shared library SONAME must match its installed filename")
    dependencies = manifest["dependencies"]
    if not isinstance(dependencies, dict):
        raise ValueError("dependencies must map module names to exact manifest hashes")
    for name, dependency in dependencies.items():
        if not NAME.fullmatch(name) or not isinstance(dependency, dict) or set(dependency) != {"sha256", "linkage", "reexport_headers"}:
            raise ValueError("invalid dependency metadata")
        if not is_hash(dependency["sha256"]) or dependency["linkage"] not in ("static", "shared") or not isinstance(dependency["reexport_headers"], bool):
            raise ValueError("invalid dependency hash, linkage or header reexport")
    return manifest, payloads


def prepare(policy_path, output, readelf="readelf"):
    policy_path = Path(policy_path).resolve()
    policy = load_policy(policy_path)
    if (platform.system(), platform.machine(), platform.libc_ver()[0]) != ("Linux", "x86_64", "glibc"):
        raise ValueError("policy host does not match this machine")
    output = Path(output).resolve()
    bp = output / "Android.bp"
    if bp.exists() and not bp.read_text().startswith(MARKER):
        raise ValueError("refusing to overwrite an Android.bp not generated by this tool")
    inspected, records = {}, {}
    policies = {item["module"]: item for item in policy["libraries"]}
    for name, item in policies.items():
        records[name] = {"module": name, "decision": "source"}
        try:
            inspected[name] = inspect_package(item, policy_path.parent, readelf)
        except (ValueError, OSError, subprocess.SubprocessError) as error:
            records[name]["reason"] = str(error)

    # Evaluate the complete closure before staging anything. Dependency versions
    # are pinned by each parent, not merely by the top-level selection policy.
    closures, visiting = {}, set()
    def closure(name):
        if name in closures:
            return closures[name]
        if name in visiting:
            raise ValueError("cyclic packaged-library dependencies")
        if name not in inspected:
            return None
        visiting.add(name)
        result = {name}
        for dep, requirement in inspected[name][0]["dependencies"].items():
            if (dep not in policies or dep not in inspected or
                    policies[dep]["sha256"] != requirement["sha256"] or
                    requirement["linkage"] not in inspected[dep][0]):
                result = None
                break
            other = closure(dep)
            if other is None:
                result = None
                break
            result.update(other)
        visiting.remove(name)
        closures[name] = result
        return result

    for name in policies:
        closure(name)
    staged = {}
    for name, package_closure in closures.items():
        if package_closure is None:
            records[name]["reason"] = "required dependency package unavailable or incompatible"
            continue
        manifest, payloads = inspected[name]
        prefix = "snapshots/" + name + "-" + policies[name]["sha256"]
        staged[name] = [prefix + "/" + filename for filename in payloads]
        for filename, payload in payloads.items():
            destination = output / prefix / filename
            destination.parent.mkdir(parents=True, exist_ok=True)
            atomic_write(destination, payload)
        records[name].update(decision="package", manifest_sha256=policies[name]["sha256"],
                             snapshot=prefix, provenance={key: manifest[key] for key in ("source_revision", "toolchain", "configuration")})

    lines = [MARKER]
    for name, item in policies.items():
        fields = {"name": name, "licenses": item["licenses"], "compile_multilib": "64",
                  "stl": "none", "unique_host_soname": False, "enabled": False,
                  "target": {HOST: {"enabled": True}}, "visibility": ["//visibility:public"]}
        if records[name]["decision"] == "package":
            manifest = inspected[name][0]
            prefix = records[name]["snapshot"]
            fields["export_include_dirs"] = [prefix + "/" + path for path in manifest["include_dirs"]]
            fields["package_files"] = sorted(file for dep in closures[name] for file in staged[dep])
            for kind in ("static", "shared"):
                fields[kind] = {"srcs": [prefix + "/" + manifest[kind]]} if kind in manifest else {"enabled": False}
                deps = {dep: req for dep, req in manifest["dependencies"].items() if req["linkage"] == kind}
                fields[kind + "_libs"] = list(deps)
                fields["export_" + kind + "_lib_headers"] = [dep for dep, req in deps.items() if req["reexport_headers"]]
            fields["strip"] = {"none": True}
        else:
            fields["srcs"] = ["unavailable/" + name]
            fields["package_files"] = ["unavailable/" + name]
        # JSON values are valid Blueprint values, except nested object keys.
        def bp_value(value, indent=4):
            if isinstance(value, dict):
                return "{\n" + "".join(" " * indent + key + ": " + bp_value(val, indent + 4) + ",\n" for key, val in value.items()) + " " * (indent - 4) + "}"
            return json.dumps(value)
        lines.append("\ncc_packaged_library_host " + bp_value(fields) + "\n")
    output.mkdir(parents=True, exist_ok=True)
    lock = {"schema_version": 1, "host": HOST, "policy_sha256": digest(policy_path.read_bytes()), "libraries": list(records.values())}
    atomic_write(output / "selection.json", (json.dumps(lock, indent=2) + "\n").encode())
    atomic_write(bp, "".join(lines).encode())
    return lock


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--policy", required=True)
    parser.add_argument("--output", required=True)
    parser.add_argument("--readelf", default="readelf")
    args = parser.parse_args()
    try:
        lock = prepare(args.policy, args.output, args.readelf)
    except (ValueError, OSError) as error:
        parser.exit(2, f"selection error: {error}\n")
    for item in lock["libraries"]:
        print(f'{item["module"]}: {item["decision"]} ({item.get("reason", item.get("snapshot"))})')


if __name__ == "__main__":
    main()
